//! FAST-9/16 against `cv2.FastFeatureDetector_create(t, nms, TYPE_9_16)`.
//!
//! * `corner_score` is OpenCV's `cornerScore<16>` (`fast_score.cpp`): the
//!   largest threshold for which the pixel is still a corner. It used to be
//!   Rosten's "sum of the arc's |differences| minus 9t", a different number on
//!   every corner and a different *ordering*.
//! * `fast_detect_opencv(img, t, true)` is OpenCV's FAST with its 3x3
//!   non-maximum suppression (a corner survives only if its score is strictly
//!   greater than all eight neighbours'; non-corners score 0), keypoint
//!   `response` = that score, `size` = 7, in raster order.
//! * With suppression off OpenCV reports every corner with `response = 0`;
//!   that is `fast_detect_opencv(img, t, false)`, and `fast_detect` returns the
//!   same positions.
//!
//! Reference values: OpenCV 4.13, `[(int(k.pt[0]), int(k.pt[1]),
//! int(k.response)) for k in det.detect(img)]` on the images built below.

use cv_features::fast::{corner_score, fast_detect, fast_detect_opencv};
use image::GrayImage;

fn lcg(n: usize, seed: u32) -> Vec<u8> {
    let mut s = seed;
    (0..n)
        .map(|_| {
            s = s.wrapping_mul(1664525).wrapping_add(1013904223);
            (s >> 24) as u8
        })
        .collect()
}

fn noise(w: u32, h: u32, seed: u32) -> GrayImage {
    GrayImage::from_raw(w, h, lcg((w * h) as usize, seed)).unwrap()
}

/// 4x4 blocks of LCG values.
fn blocks(w: u32, h: u32, seed: u32) -> GrayImage {
    let bw = w.div_ceil(4);
    let bh = h.div_ceil(4);
    let b = lcg((bw * bh) as usize, seed);
    GrayImage::from_fn(w, h, |x, y| {
        image::Luma([b[((y / 4) * bw + x / 4) as usize]])
    })
}

/// Blocks plus a small ramp, so neighbouring scores rarely tie.
fn blocky(w: u32, h: u32, seed: u32) -> GrayImage {
    let b = blocks(w, h, seed);
    GrayImage::from_fn(w, h, |x, y| {
        let v = b.get_pixel(x, y)[0] as u32 + (x * 3 + y * 5) % 9;
        image::Luma([v.min(255) as u8])
    })
}

/// Bright parallelogram bands, a mid-grey diagonal and a little texture.
fn shapes(w: u32, h: u32) -> GrayImage {
    GrayImage::from_fn(w, h, |x, y| {
        let mut v = 60 + (x + 2 * y) % 7;
        if (x / 7 + y / 5) % 3 == 0 {
            v = 200 - (x * y) % 11;
        }
        if x.abs_diff(y) < 3 {
            v = 128;
        }
        image::Luma([v as u8])
    })
}

type Expect = &'static [(u16, u16, u8)];

fn cases() -> Vec<(&'static str, GrayImage, u8, Expect, Expect)> {
    vec![
        ("noise", noise(32, 24, 5), 40, NOISE_T40_NMS, NOISE_T40_ALL),
        ("noise", noise(32, 24, 5), 90, NOISE_T90_NMS, NOISE_T90_ALL),
        (
            "blocks",
            blocks(32, 28, 9),
            10,
            BLOCKS_T10_NMS,
            BLOCKS_T10_ALL,
        ),
        (
            "blocks",
            blocks(32, 28, 9),
            30,
            BLOCKS_T30_NMS,
            BLOCKS_T30_ALL,
        ),
        (
            "blocky",
            blocky(40, 32, 11),
            15,
            BLOCKY_T15_NMS,
            BLOCKY_T15_ALL,
        ),
        ("shapes", shapes(44, 36), 20, SHAPES_T20_NMS, SHAPES_T20_ALL),
        ("shapes", shapes(44, 36), 60, SHAPES_T60_NMS, SHAPES_T60_ALL),
    ]
}

/// The response OpenCV reports for every keypoint that survives its
/// suppression is `cornerScore`, so each one pins `corner_score`.
#[test]
fn corner_score_is_opencvs_corner_score() {
    let mut checked = 0;
    for (name, img, t, nms, _) in cases() {
        for &(x, y, response) in nms {
            let got = corner_score(&img, x as i32, y as i32, t);
            assert_eq!(
                got, response as f64,
                "{name} t={t}: corner_score at ({x}, {y}) is {got}, OpenCV's response is {response}"
            );
            checked += 1;
        }
    }
    assert!(checked > 100, "only {checked} scores compared");
}

/// Without suppression OpenCV reports every corner; `fast_detect` must find
/// exactly the same set, in the same raster order.
#[test]
fn fast_detect_finds_opencvs_corners() {
    for (name, img, t, _, all) in cases() {
        let got: Vec<(u16, u16)> = fast_detect(&img, t, usize::MAX)
            .keypoints
            .iter()
            .map(|k| (k.x as u16, k.y as u16))
            .collect();
        let want: Vec<(u16, u16)> = all.iter().map(|&(x, y, _)| (x, y)).collect();
        assert_eq!(got, want, "{name} t={t}");
    }
}

#[test]

fn fast_detect_opencv_matches_opencv() {
    for (name, img, t, nms, all) in cases() {
        for (suppress, want) in [(true, nms), (false, all)] {
            let kps = fast_detect_opencv(&img, t, suppress).keypoints;
            let got: Vec<(u16, u16, u8)> = kps
                .iter()
                .map(|k| (k.x as u16, k.y as u16, k.response as u8))
                .collect();
            assert_eq!(got, want, "{name} t={t} nonmax={suppress}");
            for k in &kps {
                assert_eq!(k.size, 7.0);
                assert_eq!((k.x.fract(), k.y.fract()), (0.0, 0.0));
                assert_eq!(k.response.fract(), 0.0);
            }
        }
    }
}

