//! `welch`, `stft`, `spectrogram` against `scipy.signal` with default options.
//!
//! Before the fix all three used a *symmetric* Hann window (SciPy's
//! `get_window('hann', n)` is periodic), none removed the segment mean
//! (`welch` / `spectrogram` default `detrend='constant'`), `stft` had no
//! `1/sum(window)` scaling and no `boundary='zeros'` / `padded=True` extension,
//! and `spectrogram` used Hann with 50 % overlap where SciPy's default is
//! `('tukey', 0.25)` with `noverlap = nperseg // 8`, plus density scaling.
//! On `x = 5 + sin(0.7 i)`, 64 samples, `nperseg = 16`, `welch` returned
//! `PSD[0] = 249.9` where SciPy gives 0.175.
//!
//! Reference arrays generated with SciPy (`scipy.signal.welch`, `stft`,
//! `spectrogram`); spectrogram and STFT arrays are stored frame-major
//! (`[time][freq]`, this crate's layout), i.e. SciPy's output transposed.

use cv_signal::signal::{spectrogram, stft, welch};

fn input(n: usize) -> Vec<f64> {
    (0..n).map(|i| 5.0 + (0.7 * i as f64).sin()).collect()
}

fn close(name: &str, got: &[f64], want: &[f64], rtol: f64, atol: f64) {
    assert_eq!(got.len(), want.len(), "{name}: length");
    for (i, (g, w)) in got.iter().zip(want).enumerate() {
        assert!(
            (g - w).abs() <= atol + rtol * w.abs(),
            "{name}[{i}] = {g:e}, SciPy {w:e}"
        );
    }
}

#[test]
fn welch_matches_scipy_defaults() {
    let x = input(64);
    let (f, p) = welch(&x, 16, None, 1.0);
    close("f", &f, &WELCH_16_F, 0.0, 1e-15);
    close("psd", &p, &WELCH_16_P, 1e-10, 1e-18);

    // Odd nperseg (no Nyquist bin), explicit overlap, fs != 1.
    let (f, p) = welch(&x, 15, Some(5), 2.5);
    close("f15", &f, &WELCH_15_F, 0.0, 1e-15);
    close("psd15", &p, &WELCH_15_P, 1e-10, 1e-18);
}

#[test]
fn stft_matches_scipy_defaults() {
    let x = input(64);
    let (t, f, z) = stft(&x, 16, None, 1.0);
    close("t", &t, &STFT_T, 0.0, 1e-12);
    close("f", &f, &STFT_F, 0.0, 1e-15);
    let re: Vec<f64> = z.iter().flatten().map(|c| c.0).collect();
    let im: Vec<f64> = z.iter().flatten().map(|c| c.1).collect();
    close("re", &re, &STFT_RE, 1e-10, 1e-13);
    close("im", &im, &STFT_IM, 1e-10, 1e-13);

    // Length that needs end padding, custom overlap, fs = 2.
    let x = input(61);
    let (t, _, z) = stft(&x, 16, Some(10), 2.0);
    close("t61", &t, &STFT61_T, 0.0, 1e-12);
    let re: Vec<f64> = z.iter().flatten().map(|c| c.0).collect();
    let im: Vec<f64> = z.iter().flatten().map(|c| c.1).collect();
    close("re61", &re, &STFT61_RE, 1e-10, 1e-13);
    close("im61", &im, &STFT61_IM, 1e-10, 1e-13);
}

#[test]
fn spectrogram_matches_scipy_defaults() {
    let x = input(64);
    let (t, f, s) = spectrogram(&x, 16, None, 1.0);
    close("t", &t, &SPEC_T, 0.0, 1e-12);
    close("f", &f, &SPEC_F, 0.0, 1e-15);
    let flat: Vec<f64> = s.iter().flatten().copied().collect();
    close("S", &flat, &SPEC_S, 1e-10, 1e-18);

    let (t, _, s) = spectrogram(&x, 16, Some(8), 4.0);
    close("t2", &t, &SPEC2_T, 0.0, 1e-12);
    let flat: Vec<f64> = s.iter().flatten().copied().collect();
    close("S2", &flat, &SPEC2_S, 1e-10, 1e-18);
}

