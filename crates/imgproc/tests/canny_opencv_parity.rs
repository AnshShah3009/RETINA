//! `canny` against `cv2.Canny(img, lo, hi)` (OpenCV 4.13, aperture 3).
//!
//! Before: a σ=1 Gaussian blur was applied first, the magnitude was L2 and
//! non-maximum suppression kept `m >= m1 && m >= m2`, so a vertical step gave
//! a 2-pixel-wide edge and the edge set matched cv2 nowhere. OpenCV: no
//! blur, 3x3 Sobel with BORDER_REPLICATE, L1 magnitude `|dx| + |dy|` by
//! default, NMS strict towards the left/up neighbour (`>`), non-strict towards
//! right/down (`>=`), strict on both diagonal neighbours, thresholds strict
//! (`m > low`, `m > high`). Reference tables are cv2 output, row-major, hex.

use cv_imgproc::{canny, canny_with_options, CannyOptions};
use image::GrayImage;

fn rand_img(w: u32, h: u32, seed: u32) -> GrayImage {
    let mut s = seed;
    GrayImage::from_fn(w, h, |_, _| {
        s = s.wrapping_mul(1664525).wrapping_add(1013904223);
        image::Luma([(s >> 24) as u8])
    })
}

fn vstep() -> GrayImage {
    GrayImage::from_fn(32, 24, |x, _| image::Luma([if x < 16 { 50 } else { 200 }]))
}

fn rect() -> GrayImage {
    GrayImage::from_fn(40, 30, |x, y| {
        image::Luma([if (8..30).contains(&x) && (6..22).contains(&y) {
            180
        } else {
            30
        }])
    })
}

fn disc() -> GrayImage {
    GrayImage::from_fn(40, 40, |x, y| {
        let (dx, dy) = (x as i32 - 20, y as i32 - 20);
        image::Luma([if dx * dx + dy * dy <= 121 { 220 } else { 40 }])
    })
}

fn diag() -> GrayImage {
    GrayImage::from_fn(32, 32, |x, y| {
        image::Luma([if x + y < 30 { 60 } else { 190 }])
    })
}

fn unhex(chunks: &[&str]) -> Vec<u8> {
    let s: String = chunks.concat();
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

fn assert_same(name: &str, out: &GrayImage, expected: &[&str]) {
    let exp = unhex(expected);
    assert_eq!(out.as_raw().len(), exp.len(), "{name}: size");
    let w = out.width() as usize;
    let diffs: Vec<(usize, usize, u8, u8)> = out
        .as_raw()
        .iter()
        .zip(&exp)
        .enumerate()
        .filter(|(_, (a, b))| a != b)
        .map(|(i, (a, b))| (i % w, i / w, *a, *b))
        .collect();
    let ours = out.as_raw().iter().filter(|&&v| v != 0).count();
    let theirs = exp.iter().filter(|&&v| v != 0).count();
    assert!(
        diffs.is_empty(),
        "{name}: {} pixels differ from cv2 (ours {ours} edge px, cv2 {theirs}); first (x, y, ours, cv2): {:?}",
        diffs.len(),
        &diffs[..diffs.len().min(8)]
    );
}

#[test]
fn vertical_step_is_one_pixel_wide_like_opencv() {
    assert_same("vstep", &canny(&vstep(), 50, 150), VSTEP);
}

#[test]
fn rectangle_matches_opencv() {
    assert_same("rect", &canny(&rect(), 50, 150), RECT);
}

#[test]
fn disc_matches_opencv() {
    assert_same("disc", &canny(&disc(), 50, 150), DISC);
}

#[test]
fn diagonal_step_matches_opencv() {
    assert_same("diag", &canny(&diag(), 50, 150), DIAG);
}

#[test]
fn noise_matches_opencv() {
    // Thresholds above 255 need the f32 entry point.
    let out = canny_with_options(&rand_img(40, 30, 5), 300.0, 600.0, &CannyOptions::default());
    assert_same("noise", &out, NOISE);
}

#[test]
fn l2_gradient_matches_opencv() {
    let l2 = CannyOptions {
        l2_gradient: true,
        ..CannyOptions::default()
    };
    assert_same(
        "disc L2",
        &canny_with_options(&disc(), 50.0, 150.0, &l2),
        DISC_L2,
    );
    assert_same(
        "noise L2",
        &canny_with_options(&rand_img(40, 30, 5), 200.0, 400.0, &l2),
        NOISE_L2,
    );
}

#[test]
fn swapped_thresholds_behave_like_opencv() {
    // cv2.Canny swaps low/high when low > high.
    let out = canny_with_options(&rect(), 150.0, 50.0, &CannyOptions::default());
    assert_same("rect swapped", &out, RECT);
}

#[test]
fn optional_pre_blur_is_opt_in() {
    let blurred = CannyOptions {
        blur_sigma: Some(1.0),
        ..CannyOptions::default()
    };
    let a = canny_with_options(&vstep(), 10.0, 30.0, &blurred);
    assert!(a.pixels().any(|p| p[0] == 255));
    assert_eq!(a.dimensions(), (32, 24));
}

