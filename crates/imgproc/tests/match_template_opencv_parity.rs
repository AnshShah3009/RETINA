#[test]
fn black_window_is_not_a_perfect_sqdiff_normed_match() {
    // The exact patch at (4, 6) is the only perfect match; cv2 scores the
    // black block 1.0 ("nothing alike").
    let (img, templ) = inputs();
    let r = match_template(&img, &templ, TemplateMatchMethod::SqDiffNormed);
    assert_eq!(r.get(0, 0), 1.0);
    let ((x, y, v), _) = min_max_loc(&r);
    assert_eq!((x, y), (4, 6));
    assert!(v.abs() < 1e-6);
    assert!(r.data.iter().all(|&v| (0.0..=1.0).contains(&v)));
}

#[test]
fn degenerate_templates_match_opencv() {
    // cv2: constant template -> TM_CCOEFF_NORMED == 1 everywhere; zero
    // template -> TM_SQDIFF_NORMED == 1, TM_CCORR_NORMED == 0,
    // TM_CCOEFF_NORMED == 1 everywhere.
    let (img, _) = inputs();
    let constant = GrayImage::from_pixel(4, 3, image::Luma([77]));
    let zero = GrayImage::new(4, 3);
    for (t, m, want) in [
        (&constant, TemplateMatchMethod::CcoeffNormed, 1.0),
        (&zero, TemplateMatchMethod::SqDiffNormed, 1.0),
        (&zero, TemplateMatchMethod::CcorrNormed, 0.0),
        (&zero, TemplateMatchMethod::CcoeffNormed, 1.0),
    ] {
        let r = match_template(&img, t, m);
        assert!(
            r.data.iter().all(|&v| v == want),
            "{m:?}: expected {want} everywhere, got {:?}",
            &r.data[..4]
        );
    }
}

#[test]
fn gpu_runner_does_not_return_zeros_for_normed_methods() {
    // The WGSL kernel only implements SqDiff and Ccorr. Whatever device the
    // runner names, the normed methods must give the CPU (= cv2) result.
    let Ok(gpu) = cv_hal::gpu::GpuContext::global()
        .or_else(|_| pollster::block_on(cv_hal::gpu::GpuContext::init_global()))
    else {
        println!("no GPU adapter; skipping");
        return;
    };
    let (img, templ) = inputs();
    let runner = RuntimeRunner::Sync(gpu.device_id());
    let r = match_template_ctx(&img, &templ, TemplateMatchMethod::CcoeffNormed, &runner);
    for (a, b) in r.data.iter().zip(CCOEFF_NORMED) {
        assert!((a - b).abs() <= 5e-5, "GPU runner: {a} vs cv2 {b}");
    }
}

