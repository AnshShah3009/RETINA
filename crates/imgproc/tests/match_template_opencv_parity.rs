//! `match_template` against `cv2.matchTemplate` (OpenCV 4.13).
//!
//! OpenCV's normed methods (`common_matchTemplate`) divide by
//! `t = sqrt(window energy) * |T|` only while `|num| < t`; up to `1.125 t`
//! the score saturates to +-1, beyond it (including `t == 0`) it is 0, or 1
//! for TM_SQDIFF_NORMED. A constant template gives TM_CCOEFF_NORMED == 1
//! everywhere.
//!
//! The CPU path used to divide unconditionally and return 0 when the
//! denominator vanished, so under TM_SQDIFF_NORMED an all-black window was a
//! *perfect* match (0 where OpenCV says 1) and dark windows scored up to 600+
//! (OpenCV caps at 1). The GPU shader only implements SqDiff/Ccorr and wrote
//! 0.0 for the other four methods, which the dispatcher returned as a result.
//!
//! The 16x12 input is LCG noise with a black 6x5 block at the top-left and a
//! dim (0..3) 5x4 patch; the 4x3 template is cut from the noise at (4, 6).
//! Reference tables are cv2 output (`%.7g`). cv2 computes the
//! cross-correlation through a float DFT, so it carries ~1e-2 absolute noise
//! on the unnormalised scores (TM_CCOEFF at (11, 7): cv2 271.0156, exact
//! 271), which reaches ~2e-5 on a normed score over a dim window (exact
//! 0.3656291, cv2 0.3656502). The Rust sums are exact integers, so the
//! tolerances below allow cv2's noise and nothing more.

use cv_hal::context::{ComputeContext, TemplateMatchMethod};
use cv_imgproc::{match_template, match_template_ctx, min_max_loc};
use cv_runtime::orchestrator::RuntimeRunner;
use image::GrayImage;

