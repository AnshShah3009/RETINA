//! `fit_ellipse_ams` against `cv2.fitEllipseAMS` (OpenCV 4.13).
//!
//! AMS (Taubin) minimises `u'Au / u'Bu` with `A = sum d d'` over the conic
//! monomials `d = [x^2, xy, y^2, x, y, 1]` and `B = sum (dx dx' + dy dy')`
//! over their gradients. `B` has a zero row and column for the constant
//! term, so it is singular, and the old solver required its Cholesky factor:
//! it returned `None` for every input of 6 or more points, including points
//! sampled exactly from an ellipse. It also took the *largest* generalized
//! eigenvalue, the worst fit, where Taubin's solution is the smallest.
//!
//! cv2 reports `(w, h)` with `angle` for the `w` axis; this crate reports
//! `(major, minor)` with the major-axis angle. The comparison below reduces
//! both to centre, sorted full axes and major-axis angle mod 180.

use cv_imgproc::fit_ellipse::{EllipseResult, fit_ellipse_ams};
use nalgebra::Point2;

fn pts(v: &[[f64; 2]]) -> Vec<Point2<f64>> {
    v.iter().map(|p| Point2::new(p[0], p[1])).collect()
}

/// cv2 RotatedRect -> (cx, cy, major, minor, major-axis angle in [0, 180)).
fn cv2_ellipse(c: (f64, f64), wh: (f64, f64), angle: f64) -> [f64; 5] {
    let (major, minor, a) = if wh.0 >= wh.1 {
        (wh.0, wh.1, angle)
    } else {
        (wh.1, wh.0, angle + 90.0)
    };
    [c.0, c.1, major, minor, a.rem_euclid(180.0)]
}

fn check(name: &str, got: Option<EllipseResult>, want: [f64; 5], tol: f64) {
    let e = got.unwrap_or_else(|| panic!("{name}: fit_ellipse_ams returned None"));
    let got = [
        e.center.x,
        e.center.y,
        e.size.0.max(e.size.1),
        e.size.0.min(e.size.1),
        (e.angle + if e.size.0 >= e.size.1 { 0.0 } else { 90.0 }).rem_euclid(180.0),
    ];
    for (i, (g, w)) in got.iter().zip(&want).enumerate() {
        let d = if i == 4 {
            let d = (g - w).rem_euclid(180.0);
            d.min(180.0 - d)
        } else {
            (g - w).abs()
        };
        assert!(d <= tol, "{name}: got {got:?}, cv2 {want:?}");
    }
}

#[test]
fn exact_ellipse_is_recovered() {
    // Centre (20, 15), semi-axes 10 and 5, rotated 30 degrees; cv2 gives
    // ((20, 15), (10, 20), 120) for these 40 samples.
    let t = 30f64.to_radians();
    let p: Vec<Point2<f64>> = (0..40)
        .map(|i| {
            let a = i as f64 / 40.0 * std::f64::consts::TAU;
            let (x, y) = (10.0 * a.cos(), 5.0 * a.sin());
            Point2::new(
                20.0 + x * t.cos() - y * t.sin(),
                15.0 + x * t.sin() + y * t.cos(),
            )
        })
        .collect();
    check(
        "exact",
        fit_ellipse_ams(&p),
        cv2_ellipse((20.0, 15.0), (10.0, 20.0), 120.0),
        1e-6,
    );
}

#[test]
fn noisy_full_ellipse_matches_opencv() {
    // cv2.fitEllipseAMS -> ((20.153644561767578, 15.072792053222656),
    //   (10.223285675048828, 19.954177856445312), 118.212158203125)
    check(
        "noisy",
        fit_ellipse_ams(&pts(NOISY_FULL)),
        cv2_ellipse(
            (20.153644561767578, 15.072792053222656),
            (10.223285675048828, 19.954177856445312),
            118.212158203125,
        ),
        1e-3,
    );
}

#[test]
fn noisy_partial_arc_matches_opencv() {
    // cv2.fitEllipseAMS -> ((39.92679214477539, 30.022275924682617),
    //   (11.901399612426758, 28.042423248291016), 250.4082489013672)
    check(
        "arc",
        fit_ellipse_ams(&pts(NOISY_ARC)),
        cv2_ellipse(
            (39.92679214477539, 30.022275924682617),
            (11.901399612426758, 28.042423248291016),
            250.4082489013672,
        ),
        1e-3,
    );
}

