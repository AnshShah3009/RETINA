//! `clahe` against `cv2.createCLAHE(clip, tiles).apply(img)` (OpenCV 4.13).
//!
//! The per-tile LUT used to be equalizeHist-style,
//! `(cdf - cdf_min) / (n - cdf_min)`, so a constant 100 image went to 255.
//! OpenCV maps `cdf * 255 / tileArea`, clips at
//! `max(int(clip * tileArea / 256), 1)`, spreads the excess evenly plus a
//! residual every `256 / residual` bins, pads a non-divisible image with
//! BORDER_REFLECT_101 for the tile statistics and interpolates the four tile
//! LUTs bilinearly. Reference tables below are cv2 output, row-major, hex.

use cv_imgproc::clahe;
use image::GrayImage;

fn rand_img(w: u32, h: u32, seed: u32) -> GrayImage {
    let mut s = seed;
    GrayImage::from_fn(w, h, |_, _| {
        s = s.wrapping_mul(1664525).wrapping_add(1013904223);
        image::Luma([(s >> 24) as u8])
    })
}

fn ramp_img() -> GrayImage {
    let n = rand_img(48, 32, 3);
    GrayImage::from_fn(48, 32, |x, y| {
        image::Luma([(90 + (x * 30) / 47 + (n.get_pixel(x, y)[0] % 5) as u32) as u8])
    })
}

fn unhex(chunks: &[&str]) -> Vec<u8> {
    let s: String = chunks.concat();
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

fn check(name: &str, img: &GrayImage, clip: f32, tiles: (u32, u32), expected: &[&str]) {
    let out = clahe(img, clip, tiles);
    let exp = unhex(expected);
    assert_eq!(out.as_raw().len(), exp.len(), "{name}: size");
    let mut max_diff = 0i32;
    let mut n_diff = 0usize;
    for (a, b) in out.as_raw().iter().zip(&exp) {
        let d = (*a as i32 - *b as i32).abs();
        max_diff = max_diff.max(d);
        n_diff += (d != 0) as usize;
    }
    assert!(
        max_diff == 0,
        "{name}: max |diff| vs cv2 = {max_diff}, {n_diff} pixels differ"
    );
}

#[test]
fn constant_image_matches_opencv() {
    // cv2.createCLAHE(40, (8, 8)).apply(full((64, 64), 100)) == 143 everywhere.
    let img = GrayImage::from_pixel(64, 64, image::Luma([100]));
    check("constant_100", &img, 40.0, (8, 8), CONSTANT_100_64X64);
}

#[test]
fn random_divisible_matches_opencv() {
    check(
        "random_40x30",
        &rand_img(40, 30, 7),
        2.0,
        (4, 3),
        RANDOM_40X30_CLIP2_T4X3,
    );
}

#[test]
fn random_non_divisible_matches_opencv() {
    check(
        "random_37x29",
        &rand_img(37, 29, 11),
        3.0,
        (4, 4),
        RANDOM_37X29_CLIP3_T4X4,
    );
}

