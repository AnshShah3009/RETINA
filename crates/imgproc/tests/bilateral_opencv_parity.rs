//! `bilateral_filter_rgb` and `bilateral_filter_depth` must produce what
//! `cv2.bilateralFilter` does (OpenCV's `bilateralFilter_8u` for 3-channel
//! `u8`, `bilateralFilter_32f` for 1-channel `f32`).
//!
//! The same three divergences fixed in `cv_photo::bilateral_filter` were here:
//!
//! * **Kernel support.** OpenCV keeps only the offsets with
//!   `sqrt(dx² + dy²) <= radius` (a disc), not the whole square box.
//! * **Border.** OpenCV pads with `BORDER_DEFAULT` (reflect-101) and always
//!   averages the full disc; skipping out-of-image taps renormalised over
//!   fewer neighbours.
//! * **Radius.** `kernel_size / 2` for `kernel_size > 0`, otherwise
//!   `cvRound(1.5 * sigma_space)`, and never below 1 (so `kernel_size = 1`
//!   still filters a radius-1 disc).
//!
//! Plus one specific to the colour path: OpenCV's colour distance for a
//! 3-channel `u8` image is the **L1** distance `|db| + |dg| + |dr|`, squared
//! inside the Gaussian, not the L2 distance `db² + dg² + dr²`.
//!
//! The crate's `sigma_range` is normalised to `[0, 1]` intensity for the `u8`
//! path, so the OpenCV call is `cv2.bilateralFilter(img, d,
//! np.float32(sigma_range) * np.float32(255), sigma_space)`; for depth it is in
//! depth units and passed straight through.
//!
//! Reference values: OpenCV 4.13 on the images built by [`lcg`].

use cv_imgproc::{BilateralFilterParams, bilateral_filter_depth, bilateral_filter_rgb};

/// The LCG texture the reference was computed on (`s = s*1664525 + 1013904223`,
/// byte = `s >> 24`).
fn lcg(n: usize, seed: u32) -> Vec<u8> {
    let mut s = seed;
    (0..n)
        .map(|_| {
            s = s.wrapping_mul(1664525).wrapping_add(1013904223);
            (s >> 24) as u8
        })
        .collect()
}

const W: u32 = 11;
const H: u32 = 9;
const DW: u32 = 12;
const DH: u32 = 10;

fn params(kernel_size: i32, sigma_range: f32, sigma_space: f32) -> BilateralFilterParams {
    BilateralFilterParams {
        kernel_size,
        sigma_space,
        sigma_range,
    }
}

#[test]
fn rgb_matches_opencv_exactly() {
    let img = lcg((W * H * 3) as usize, 1);
    let cases: [(i32, f32, f32, &[u8]); 6] = [
        (5, 0.1, 3.0, &RGB_0),
        (3, 0.2, 2.0, &RGB_1),
        (0, 0.12, 1.5, &RGB_2),
        (4, 0.3, 5.0, &RGB_3),
        (1, 0.1, 3.0, &RGB_4),
        (9, 0.4, 2.5, &RGB_5),
    ];
    for (d, sr, ss, want) in cases {
        let got = bilateral_filter_rgb(&img, W, H, params(d, sr, ss));
        let diffs: Vec<(usize, u8, u8)> = got
            .iter()
            .zip(want)
            .enumerate()
            .filter(|(_, (g, w))| g != w)
            .map(|(i, (g, w))| (i, *g, *w))
            .collect();
        assert!(
            diffs.is_empty(),
            "d={d} sigma_range={sr} sigma_space={ss}: {} of {} bytes differ from OpenCV, \
             first (index, got, opencv): {:?}",
            diffs.len(),
            got.len(),
            &diffs[..diffs.len().min(8)]
        );
    }
}

/// A one-pixel-wide image: every tap off the centre column is outside the
/// image and must come back through reflect-101 (for width 1, column 0).
#[test]
fn rgb_single_column_matches_opencv() {
    let col: Vec<u8> = [10u8, 200, 90, 40]
        .iter()
        .flat_map(|&v| [v, v, v])
        .collect();
    let got = bilateral_filter_rgb(&col, 1, 4, params(5, 0.4, 3.0));
    assert_eq!(got, [12, 12, 12, 200, 200, 200, 82, 82, 82, 55, 55, 55]);
}

/// `bilateralFilter_32f` interpolates its colour weight from a 4096-bin
/// table over the image's value range, so the f32 output is compared to a
/// tolerance rather than bit for bit. The divergences above moved values by
/// whole tenths.
#[test]
fn depth_matches_opencv() {
    let depth: Vec<f32> = lcg((DW * DH) as usize, 7)
        .into_iter()
        .map(|b| b as f32 / 255.0 * 4.0 + 0.5)
        .collect();
    let cases: [(i32, f32, f32, &[f32]); 3] = [
        (5, 0.5, 3.0, &DEPTH_0),
        (3, 0.25, 2.0, &DEPTH_1),
        (0, 1.0, 1.5, &DEPTH_2),
    ];
    for (d, sr, ss, want) in cases {
        let got = bilateral_filter_depth(&depth, DW, DH, params(d, sr, ss));
        let worst = got
            .iter()
            .zip(want)
            .map(|(g, w)| (g - w).abs())
            .fold(0.0f32, f32::max);
        assert!(
            worst <= 1e-5,
            "d={d} sigma_range={sr} sigma_space={ss}: max |rust - opencv| = {worst}"
        );
    }
}

