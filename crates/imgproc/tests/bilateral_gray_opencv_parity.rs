//! `bilateral_filter_gray` must produce what `cv2.bilateralFilter` does on an
//! 8-bit single-channel image (OpenCV's `bilateralFilter_8u`, `cn = 1`), byte
//! for byte. `cv_photo::bilateral_filter` delegates to it, so
//! `crates/photo/tests/bilateral_opencv_parity.rs` pins the same function on a
//! second image.
//!
//! The cases cover the radius rule: `d > 0`, `d = 0`, negative `d` (both
//! `cvRound(1.5 * sigma_space)`) and `d = 1` (radius clamped up to 1).
//! `sigma_color` is absolute grey levels, passed to OpenCV unchanged.
//!
//! Reference values: OpenCV 4.13 with `cv2.ipp.setUseIPP(False)`,
//! `cv2.bilateralFilter(img, d, sigma_color, sigma_space)` on the 23x17 image
//! built by [`input`]. With IPP enabled, OpenCV hands this image to
//! `ippiFilterBilateral`, which rounds differently (off by one on about half
//! the pixels for `d = 5`); the references are OpenCV's own
//! `bilateralFilter_8u`.

