#[test]
fn gray_bilateral_matches_opencv_exactly() {
    let img = input();
    let mut failures = Vec::new();
    for &(d, sigma_color, sigma_space, expected) in CASES {
        let out = bilateral_filter_gray(&img, d, sigma_color, sigma_space);
        assert_eq!(out.dimensions(), (W, H));
        let mismatches: Vec<_> = out
            .as_raw()
            .iter()
            .zip(expected)
            .enumerate()
            .filter(|(_, (got, want))| got != want)
            .map(|(i, (got, want))| (i as u32 % W, i as u32 / W, *got, *want))
            .collect();
        if !mismatches.is_empty() {
            failures.push(format!(
                "d={d} sigma_color={sigma_color} sigma_space={sigma_space}: {} pixels differ, \
                 first (x, y, got, want) = {:?}",
                mismatches.len(),
                mismatches[0]
            ));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

/// A non-positive sigma is replaced by 1, the rule inside OpenCV's
/// `bilateralFilter_8u` and the one `cv_photo::bilateral_filter` has always
/// documented.
///
/// OpenCV 4.13's `cv::bilateralFilter` entry point no longer reaches that
/// rule: with either sigma `<= 0` it returns a copy of the input. Following it
/// would change this function's documented behaviour (and the shared kernel of
/// the colour and depth filters), so it is left as a follow-up.
#[test]
fn non_positive_sigma_is_replaced_by_one() {
    let img = input();
    for (d, sigma_color, sigma_space) in [(7, 0.0f32, 3.0f32), (5, -4.0, 3.0), (0, 30.0, 0.0)] {
        let got = bilateral_filter_gray(&img, d, sigma_color, sigma_space);
        let want = bilateral_filter_gray(
            &img,
            d,
            if sigma_color > 0.0 { sigma_color } else { 1.0 },
            if sigma_space > 0.0 { sigma_space } else { 1.0 },
        );
        assert_eq!(
            got, want,
            "d={d} sigma_color={sigma_color} sigma_space={sigma_space}"
        );
    }
}

#[test]
fn empty_images_stay_empty() {
    for (w, h) in [(0, 0), (0, 5), (5, 0)] {
        let out = bilateral_filter_gray(&GrayImage::new(w, h), 5, 30.0, 3.0);
        assert_eq!(out.dimensions(), (w, h));
    }
}
